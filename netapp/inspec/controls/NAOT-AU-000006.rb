control 'NAOT-AU-000006' do
  title 'ONTAP must record time stamps for audit records that can be mapped to Coordinated Universal Time (UTC) or Greenwich Mean Time (GMT).'
  desc 'If time stamps are not consistently applied and there is no common time reference, it is difficult to perform forensic analysis.

Time stamps generated by the application include date and time. Time is commonly expressed in Coordinated Universal Time (UTC), a modern continuation of Greenwich Mean Time (GMT), or local time with an offset from UTC.'
  desc 'check', 'Use "cluster date show" to see the current time zone configured.

If ONTAP is not configured to record time stamps for audit records that can be mapped to Coordinated Universal Time (UTC) or Greenwich Mean Time (GMT), this is a finding.'
  desc 'fix', 'Configure the time zone to UTC with "cluster date modify -timezone UTC".'
  impact 0.5
  tag check_id: 'C-50370r860681_chk'
  tag severity: 'medium'
  tag gid: 'V-246938'
  tag rid: 'SV-246938r961443_rule'
  tag stig_id: 'NAOT-AU-000006'
  tag gtitle: 'SRG-APP-000374-NDM-000299'
  tag fix_id: 'F-50324r860682_fix'
  tag 'documentable'
  tag cci: ['CCI-001890']
  tag nist: ['AU-8 b']

  cmd = ontap_command('rows 0; cluster date show')

  describe cmd do
    let(:non_utc_entries) do
      node_date_lines = cmd.stdout.lines.select { |l| l =~ /[+-]\d{2}:\d{2}/ }
      node_date_lines.reject { |l| l =~ /\b(UTC|GMT)\b/i }
    end

    it 'must have all cluster nodes synchronized to UTC or GMT' do
      expect(cmd.stdout).to match(/[+-]\d{2}:\d{2}\s+(UTC|GMT)/i), 'No UTC or GMT time configuration found in output.'
      expect(non_utc_entries).to be_empty, "Non-UTC node configurations detected: #{non_utc_entries.map(&:strip).join(', ')}"
    end
  end

  describe 'NOT A CHECK: FOR MANUAL REVIEW OF OUTPUT' do
    skip <<~EVIDENCE 

      --- RAW OUTPUT FOR MANUAL VERIFICATION ---
      #{cmd}
      #{cmd.stdout.encode('UTF-8')}
    EVIDENCE
  end
end